export function getClubCrestUrl(clubId?: string, clubName?: string): string | undefined {
  if (clubId && CLUB_CREST_MAP[clubId]) return CLUB_CREST_MAP[clubId];
  if (clubName) {
    if (CAREER_EXTRA_CLUB_LOGOS[clubName]) return CAREER_EXTRA_CLUB_LOGOS[clubName];
    const normalizedName = clubName.replace(/\s*\((Efsane|Emekli)\)\s*$/i, '').trim();
    if (CAREER_EXTRA_CLUB_LOGOS[normalizedName]) {
      return CAREER_EXTRA_CLUB_LOGOS[normalizedName];
    }
  }
  return undefined;
}
