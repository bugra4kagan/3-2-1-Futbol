function resolveSilhouettePose(player: Player): SilhouettePose {
  if (player.position === 'GK') return 'gk_save';
  if (player.position === 'DF') return 'captain';
  if (player.position === 'MF') return 'dribble';
  return (player.shirtNumber ?? 9) % 2 === 0 ? 'arms_wide' : 'sniper';
}

function resolveHintClubId(player: Player): string {
  if (player.clubId && CLUBS[player.clubId]) return player.clubId;
  const fromHistory = (player.careerHistory || []).find(
    (entry) => entry.clubId && CLUBS[entry.clubId]
  );
  return fromHistory?.clubId || 'galatasaray';
}

